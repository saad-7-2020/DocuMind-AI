"""Initial schema (docs/architecture.md §8).

Written as plain SQL on purpose: it is the reference DDL for the project and is
easier to read and review than autogenerated operations.

Revision ID: 0001
Revises:
Create Date: 2026-10-16
"""

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

UPGRADE = r"""
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS unaccent;

-- French full-text search: strip accents, then apply the French Snowball stemmer.
CREATE TEXT SEARCH CONFIGURATION documind_fr (COPY = french);
ALTER TEXT SEARCH CONFIGURATION documind_fr
    ALTER MAPPING FOR hword, hword_part, word WITH unaccent, french_stem;

CREATE TABLE users (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email       text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE api_keys (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    key_prefix  text NOT NULL,
    key_hash    bytea NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    revoked_at  timestamptz
);

CREATE TABLE documents (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id       uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    filename       text NOT NULL,
    mime_type      text NOT NULL CHECK (mime_type IN (
                     'application/pdf',
                     'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
                     'text/plain')),
    size_bytes     bigint NOT NULL CHECK (size_bytes > 0),
    sha256         char(64) NOT NULL,
    storage_key    text NOT NULL,
    status         text NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending','processing','ready','failed','deleting')),
    error_code     text,
    page_count     int,
    ocr_page_count int NOT NULL DEFAULT 0,
    language       text NOT NULL DEFAULT 'fr',
    title          text,
    metadata       jsonb NOT NULL DEFAULT '{}',
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (owner_id, sha256)
);
CREATE INDEX documents_owner_status ON documents (owner_id, status);
CREATE INDEX documents_owner_created ON documents (owner_id, created_at DESC, id DESC);

CREATE TABLE document_pages (
    document_id        uuid NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    page_number        int  NOT NULL CHECK (page_number >= 1),
    text               text NOT NULL,
    extraction_method  text NOT NULL CHECK (extraction_method IN ('text_layer','ocr','docx','plain')),
    ocr_confidence     real,
    char_offset        int  NOT NULL,
    PRIMARY KEY (document_id, page_number)
);

CREATE TABLE chunks (
    id                  uuid PRIMARY KEY,
    document_id         uuid NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    owner_id            uuid NOT NULL,
    chunk_index         int  NOT NULL,
    page_start          int  NOT NULL,
    page_end            int  NOT NULL CHECK (page_end >= page_start),
    char_start          int  NOT NULL,
    char_end            int  NOT NULL CHECK (char_end > char_start),
    section_path        text,
    text                text NOT NULL,
    token_count         int  NOT NULL,
    chunker_config_hash text NOT NULL,
    embedding_model     text NOT NULL,
    embedding           vector(1024) NOT NULL,
    fts_config          regconfig NOT NULL DEFAULT 'documind_fr',
    tsv                 tsvector GENERATED ALWAYS AS (to_tsvector(fts_config, text)) STORED,
    created_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (document_id, chunk_index)
);
CREATE INDEX chunks_embedding_hnsw ON chunks USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);
CREATE INDEX chunks_tsv_gin   ON chunks USING gin (tsv);
CREATE INDEX chunks_owner_doc ON chunks (owner_id, document_id);

-- Jobs keep their own owner_id and survive document deletion (document_id -> NULL),
-- so a finished delete job can still be polled.
CREATE TABLE jobs (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id      uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    document_id   uuid REFERENCES documents(id) ON DELETE SET NULL,
    kind          text NOT NULL CHECK (kind IN ('ingest','reindex','delete')),
    status        text NOT NULL DEFAULT 'queued'
                    CHECK (status IN ('queued','running','succeeded','failed')),
    stage         text,
    progress      real NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 1),
    attempts      int  NOT NULL DEFAULT 0,
    max_attempts  int  NOT NULL DEFAULT 3,
    run_after     timestamptz NOT NULL DEFAULT now(),
    locked_by     text,
    locked_at     timestamptz,
    last_error    text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX jobs_claimable ON jobs (run_after) WHERE status = 'queued';

CREATE TABLE query_logs (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id          uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question          text NOT NULL,
    config            jsonb NOT NULL,
    answer            jsonb,
    abstained         boolean NOT NULL,
    abstention_gate   smallint,
    latency_ms        jsonb NOT NULL,
    input_tokens      int,
    output_tokens     int,
    cost_usd          numeric(10,6),
    citations_dropped int NOT NULL DEFAULT 0,
    error_code        text,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE query_retrievals (
    query_id   uuid NOT NULL REFERENCES query_logs(id) ON DELETE CASCADE,
    stage      text NOT NULL CHECK (stage IN ('dense','keyword','fused','reranked','context')),
    rank       int  NOT NULL,
    chunk_id   uuid NOT NULL,
    score      double precision NOT NULL,
    PRIMARY KEY (query_id, stage, rank)
);

CREATE TABLE eval_runs (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name            text NOT NULL,
    dataset_name    text NOT NULL,
    dataset_sha256  char(64) NOT NULL,
    git_commit      text NOT NULL,
    config          jsonb NOT NULL,
    model_versions  jsonb NOT NULL,
    status          text NOT NULL CHECK (status IN ('running','succeeded','failed')),
    summary         jsonb,
    started_at      timestamptz NOT NULL DEFAULT now(),
    finished_at     timestamptz
);

CREATE TABLE eval_items (
    run_id        uuid NOT NULL REFERENCES eval_runs(id) ON DELETE CASCADE,
    question_id   text NOT NULL,
    retrieved     jsonb NOT NULL,
    response      jsonb,
    metrics       jsonb NOT NULL,
    latency_ms    jsonb NOT NULL,
    input_tokens  int,
    output_tokens int,
    cost_usd      numeric(10,6),
    PRIMARY KEY (run_id, question_id)
);
"""

DOWNGRADE = r"""
DROP TABLE IF EXISTS eval_items, eval_runs, query_retrievals, query_logs, jobs, chunks,
    document_pages, documents, api_keys, users;
DROP TEXT SEARCH CONFIGURATION IF EXISTS documind_fr;
"""


def upgrade() -> None:
    op.execute(UPGRADE)


def downgrade() -> None:
    op.execute(DOWNGRADE)
