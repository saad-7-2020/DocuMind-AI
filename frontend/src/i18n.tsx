const DICTS: Record<Lang, Record<Key, string>> = { fr, en };
const STORAGE = "documind.lang";

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE);
    if (saved === "fr" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return (navigator.language || "fr").toLowerCase().startsWith("fr") ? "fr" : "en";
}

let current: Lang = initialLang();

/** Translate outside React components (API error messages, formatting). */
export function translate(key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTS[current][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export const currentLang = (): Lang => current;
export const locale = (): string => (current === "fr" ? "fr-FR" : "en-GB");

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18n>({ lang: current, setLang: () => {}, t: translate });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current);
  const setLang = useCallback((l: Lang) => {
    current = l;
    document.documentElement.lang = l;
    try { localStorage.setItem(STORAGE, l); } catch { /* ignore */ }
    setLangState(l);
  }, []);
  const value = useMemo<I18n>(() => {
    document.documentElement.lang = lang;
    return { lang, setLang, t: translate };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
